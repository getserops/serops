"""PR-N (2026-09-21): backfill IncidentNotificationChannel rows from
each org's legacy NotificationSettings.

Rationale (see memory ``pr-notifications-cleanup``): the target is
one uniform delivery-target table (Grafana / Alertmanager pattern).
This migration mirrors the org's existing email/slack/teams config
onto IncidentNotificationChannel so the new surface is data-parity
with the old before a later PR retires ``org_settings.NotificationSettings``.

Idempotent: names include the source discriminator ('email',
'slack', 'teams') and we ``get_or_create`` on (organisation, name).
Re-running the migration doesn't produce duplicates.

Never fails: if an org has no NotificationSettings row, skip. If the
webhook re-encryption fails, log + skip that one channel.
"""

from django.db import migrations


def backfill_channels(apps, schema_editor):
    NotificationSettings = apps.get_model('org_settings', 'NotificationSettings')
    IncidentChannel = apps.get_model('notifications', 'IncidentNotificationChannel')

    # Import encryption + resolve inside the function so the migration
    # doesn't blow up if providers.encryption is unavailable during
    # ``makemigrations`` diffs.
    try:
        from providers.encryption import encrypt_value
    except Exception:
        encrypt_value = None

    for ns in NotificationSettings.objects.all().iterator():
        org = ns.organisation
        # Derive a min_severity flag matching the org's toggle set.
        min_sev = ''
        if ns.notify_on_critical and not ns.notify_on_warning:
            min_sev = 'CRITICAL'
        # else: honour "any severity"

        # 1. Email
        if ns.email_enabled:
            IncidentChannel.objects.get_or_create(
                organisation=org, name='Org default email',
                defaults={
                    'kind': 'email',
                    'extra_config': {
                        # PR-N follow-up: real recipient config still
                        # comes from user preferences today. This row
                        # is a stand-in that the settings UI can edit
                        # to attach ``extra_config['to']`` later.
                        'to': [],
                        'sender_name': ns.sender_name or '',
                        'legacy_source': 'org_settings.NotificationSettings',
                    },
                    'min_severity': min_sev,
                    'is_active': True,
                },
            )

        # 2. Slack
        if ns.slack_enabled and ns.slack_webhook_url:
            enc = encrypt_value(ns.slack_webhook_url) if encrypt_value else ns.slack_webhook_url
            IncidentChannel.objects.get_or_create(
                organisation=org, name='Org default Slack',
                defaults={
                    'kind': 'slack',
                    'webhook_url': enc,
                    'extra_config': {'legacy_source': 'org_settings.NotificationSettings'},
                    'min_severity': min_sev,
                    'is_active': True,
                },
            )

        # 3. Teams
        if ns.teams_enabled and ns.teams_webhook_url:
            enc = encrypt_value(ns.teams_webhook_url) if encrypt_value else ns.teams_webhook_url
            IncidentChannel.objects.get_or_create(
                organisation=org, name='Org default Teams',
                defaults={
                    'kind': 'teams',
                    'webhook_url': enc,
                    'extra_config': {'legacy_source': 'org_settings.NotificationSettings'},
                    'min_severity': min_sev,
                    'is_active': True,
                },
            )


def unbackfill_channels(apps, schema_editor):
    """Reverse: delete channels this migration created (marked via legacy_source)."""
    IncidentChannel = apps.get_model('notifications', 'IncidentNotificationChannel')
    IncidentChannel.objects.filter(
        extra_config__legacy_source='org_settings.NotificationSettings',
    ).delete()


class Migration(migrations.Migration):
    dependencies = [
        ('notifications', '0003_incidentnotificationchannel'),
        ('org_settings', '0018_organisationapikey_extra_config'),
    ]

    operations = [
        # Add 'email' to KIND_CHOICES on the model. AlterField is
        # generated by makemigrations; we inline it here so the whole
        # PR-N backfill lands atomically.
        migrations.AlterField(
            model_name='incidentnotificationchannel',
            name='kind',
            field=__import__('django.db.models', fromlist=['CharField']).CharField(
                choices=[
                    ('slack', 'Slack'),
                    ('teams', 'Microsoft Teams'),
                    ('pagerduty', 'PagerDuty'),
                    ('opsgenie', 'OpsGenie'),
                    ('email', 'Email'),
                ],
                max_length=32,
            ),
        ),
        migrations.RunPython(backfill_channels, reverse_code=unbackfill_channels),
    ]
