"""Make a trace's identity (organisation, trace_id) instead of a global trace_id.

Security review 2026-11, finding 1: ``Trace.trace_id`` was the primary key,
so trace ids were global across tenants. Org A ingesting a trace id that
org B already had attached A's spans to B's trace and changed B's rollups.

This migration gives ``traces_trace`` a surrogate bigint ``id`` primary key,
re-points ``traces_span.trace_id`` at it (existing spans are remapped through
the old trace_id, so no row loses its data), and adds a unique constraint on
(organisation, trace_id).

The column swap is raw SQL (Postgres only, like the JSONB columns in this
app): Django cannot move a primary key that a foreign key references in one
AlterField. Constraint and index names are read through introspection so the
migration works whatever names 0001 produced.

Irreversible: once two organisations hold the same trace id, the old global
key can no longer be restored.
"""

from django.db import migrations, models


def _drop_on_column(cursor, introspection, table, column, *, keep_primary=False):
    for name, info in introspection.get_constraints(cursor, table).items():
        if info['columns'] != [column]:
            continue
        if info['primary_key'] and keep_primary:
            continue
        if info['primary_key'] or info['foreign_key'] or info['unique'] or info['check']:
            cursor.execute(f'ALTER TABLE {table} DROP CONSTRAINT "{name}"')
        elif info['index']:
            cursor.execute(f'DROP INDEX "{name}"')


def swap_trace_primary_key(apps, schema_editor):
    connection = schema_editor.connection
    introspection = connection.introspection
    with connection.cursor() as cursor:
        # Span side first: the FK (and its indexes) pin the old primary key.
        _drop_on_column(cursor, introspection, 'traces_span', 'trace_id')
        # Then the old primary key and the varchar_pattern_ops index next to it.
        _drop_on_column(cursor, introspection, 'traces_trace', 'trace_id')

        # Identity columns are filled for existing rows when added.
        cursor.execute(
            'ALTER TABLE traces_trace '
            'ADD COLUMN id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
        )

        cursor.execute('ALTER TABLE traces_span ADD COLUMN trace_ref bigint')
        # The old trace_id was globally unique, so this join maps each span
        # to exactly one trace.
        cursor.execute(
            'UPDATE traces_span s SET trace_ref = t.id '
            'FROM traces_trace t WHERE t.trace_id = s.trace_id'
        )
        # The FK made orphans impossible; this only guards NOT NULL below.
        cursor.execute('DELETE FROM traces_span WHERE trace_ref IS NULL')
        cursor.execute('ALTER TABLE traces_span DROP COLUMN trace_id')
        cursor.execute('ALTER TABLE traces_span RENAME COLUMN trace_ref TO trace_id')
        cursor.execute('ALTER TABLE traces_span ALTER COLUMN trace_id SET NOT NULL')
        cursor.execute('CREATE INDEX traces_span_trace_id_idx ON traces_span (trace_id)')
        cursor.execute(
            'ALTER TABLE traces_span ADD CONSTRAINT traces_span_trace_id_fk_traces_trace_id '
            'FOREIGN KEY (trace_id) REFERENCES traces_trace (id) DEFERRABLE INITIALLY DEFERRED'
        )


class Migration(migrations.Migration):

    dependencies = [
        ('traces', '0002_alter_ingestkey_id_alter_span_id'),
    ]

    operations = [
        # Constraints that include the span FK column go before the swap and
        # come back after it.
        migrations.AlterUniqueTogether(name='span', unique_together=set()),
        migrations.RemoveIndex(model_name='span', name='span_trace_start_idx'),
        migrations.SeparateDatabaseAndState(
            database_operations=[
                migrations.RunPython(swap_trace_primary_key),
            ],
            state_operations=[
                migrations.AddField(
                    model_name='trace',
                    name='id',
                    field=models.BigAutoField(primary_key=True, serialize=False),
                    preserve_default=False,
                ),
                migrations.AlterField(
                    model_name='trace',
                    name='trace_id',
                    field=models.CharField(max_length=32),
                ),
            ],
        ),
        migrations.AddConstraint(
            model_name='trace',
            constraint=models.UniqueConstraint(
                fields=('organisation', 'trace_id'), name='trace_org_trace_id_uniq',
            ),
        ),
        migrations.AlterUniqueTogether(name='span', unique_together={('trace', 'span_id')}),
        migrations.AddIndex(
            model_name='span',
            index=models.Index(fields=['trace', 'start_time'], name='span_trace_start_idx'),
        ),
    ]
