def _database_config_from_url(url):
    """Parse a ``postgres://user:pass@host:port/name`` URL into Django's dict.

    Kubernetes deployments hand out one connection string, not five discrete
    variables — it is what a Secret naturally holds and what every Helm chart,
    operator and PaaS emits. The SerOps chart was already shipping
    ``DATABASE_URL``, but nothing in the app read it, so a chart-deployed
    backend silently fell back to the DB_* defaults and connected to
    localhost.

    Parsed with stdlib ``urllib`` rather than adding dj-database-url: the
    format is simple and a new runtime dependency for ten lines is a poor
    trade. Returns None for anything unparseable so the caller can fall back
    to the discrete variables instead of dying at import time.
    """
    from urllib.parse import unquote, urlparse

    try:
        parsed = urlparse(url)
    except ValueError:
        return None
    if parsed.scheme not in ('postgres', 'postgresql', 'psql'):
        return None
    name = (parsed.path or '').lstrip('/')
    if not name or not parsed.hostname:
        return None
    return {
        'NAME': name,
        # Credentials are percent-encoded in a URL; a password containing
        # @ / : / # is legal and common in generated secrets.
        'USER': unquote(parsed.username) if parsed.username else '',
        'PASSWORD': unquote(parsed.password) if parsed.password else '',
        'HOST': parsed.hostname,
        'PORT': str(parsed.port) if parsed.port else '',
    }


# DATABASE_URL wins when set and parseable; DB_* remains the documented path
# for docker-compose, which sets the five variables individually. These are two
# supported deployment styles, not a legacy fallback — compose installs are
# unaffected by this.
_database_url = os.getenv('DATABASE_URL', '').strip()
_db_from_url = _database_config_from_url(_database_url) if _database_url else None

if _database_url and _db_from_url is None:
    # Loud, because the alternative is connecting somewhere unintended.
    import warnings
    warnings.warn(
        'DATABASE_URL is set but could not be parsed; falling back to DB_* '
        'environment variables. Expected postgres://user:password@host:port/dbname',
        RuntimeWarning,
    )

DATABASES = {
    'default': {
        'ENGINE': 'django.db.backends.postgresql',
        **(_db_from_url or {
            'NAME': os.getenv('DB_NAME'),
            'USER': os.getenv('DB_USER'),
            'PASSWORD': os.getenv('DB_PASSWORD'),
            'HOST': os.getenv('DB_HOST'),
            'PORT': os.getenv('DB_PORT'),
        }),
        'CONN_MAX_AGE': 300,  # Reuse DB connections for 5 min
        'CONN_HEALTH_CHECKS': True,  # Verify connection is alive before reuse
    },
}





